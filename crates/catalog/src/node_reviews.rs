//! The `node_reviews` table — per-node review status.
//!
//! One row per reviewed node, keyed by `(intake_id, scope)`. Each
//! pipeline pass rewrites the row's `notes` with its audit report
//! through [`Catalog::record_pipeline_review`]; the status moves only
//! through [`Catalog::upsert_review`], and a pass never moves it off a
//! verdict a human or LLM has given.
//!
//! Status is **strictly a human/LLM judgement**. The audit's plausibility
//! verdict lives elsewhere (`node_publication_attrs.confidence` and the
//! per-field grades returned from [`bookrack_metadata::audit`]). The
//! audit can flag a record as `low` confidence, but it can never declare
//! the record reviewed: only a human or an LLM acting on a human's
//! behalf can advance status away from [`STATUS_PENDING`]. Metadata
//! correctness is irreducibly a human concern — no extractor or
//! heuristic can promise it — so the table keeps the two axes apart.
//!
//! `reviewed_by` carries a `<namespace>:<id>` token by convention. The
//! ingest pipeline writes `bookrack-ingest:<profile-name>` (e.g.
//! `bookrack-ingest:default` or `bookrack-ingest:trust-source`) so a
//! query can tell apart the audit-profile flavours of a `pending` row.
//! Human and LLM advancers overwrite this column with their own
//! namespaced token (`human:<email>`, `llm:<model>@<version>`), and a
//! later pipeline pass leaves their token in place.
//!
//! There is no DDL CHECK on `status`; the column carries one of four
//! tokens by convention:
//!
//! - [`STATUS_PENDING`] `pending` — the pipeline inserts this on every
//!   fresh ingest. It means "no human/LLM has confirmed this record".
//! - [`STATUS_APPROVED`] `approved` — a human/LLM read the record and
//!   confirmed the metadata is correct.
//! - [`STATUS_ACKNOWLEDGED`] `acknowledged` — a human/LLM looked at an
//!   audit-flagged gap and decided to let it through anyway (the
//!   `metadata ack` flow).
//! - [`STATUS_REJECTED`] `rejected` — a human/LLM rejected the book
//!   outright.

use std::collections::BTreeMap;

use bookrack_core::ItemKind;
use bookrack_dbkit::{ColumnSpec, TableSpec};
use rusqlite::{OptionalExtension, Row, ToSql, named_params, params_from_iter};

use crate::{Catalog, Result, count_as_u64};

/// `node_reviews.status` value the pipeline writes after a fresh ingest.
/// Means "no human or LLM has confirmed this record". The pipeline never
/// writes any other value.
pub const STATUS_PENDING: &str = "pending";

/// `node_reviews.status` value a human or LLM writes when the metadata
/// has been read and confirmed correct.
pub const STATUS_APPROVED: &str = "approved";

/// `node_reviews.status` value a human or LLM writes when an audit gap
/// is known and deliberately let through (the `metadata ack` flow).
pub const STATUS_ACKNOWLEDGED: &str = "acknowledged";

/// `node_reviews.status` value a human or LLM writes when the book is
/// rejected outright.
pub const STATUS_REJECTED: &str = "rejected";

/// Every value `node_reviews.status` carries, built from the four
/// constants above so a filter validating caller input and the writers
/// cannot name different sets.
pub const REVIEW_STATUSES: [&str; 4] = [
    STATUS_PENDING,
    STATUS_APPROVED,
    STATUS_ACKNOWLEDGED,
    STATUS_REJECTED,
];

/// The single source of truth for the `node_reviews` table's schema. Its
/// DDL is rendered from this spec.
pub(crate) const SPEC: TableSpec = TableSpec {
    name: "node_reviews",
    comment: Some("Per-node review status."),
    columns: &[
        ColumnSpec::int("intake_id").not_null(),
        ColumnSpec::text("scope").not_null(),
        ColumnSpec::text("reviewed_at").not_null(),
        ColumnSpec::text("reviewed_by").not_null(),
        ColumnSpec::text("status")
            .not_null()
            .comment("pending / approved / acknowledged / rejected"),
        ColumnSpec::text("notes"),
    ],
    composite_pk: Some(&["intake_id", "scope"]),
    uniques: &[],
    table_checks: &[],
    indexes: &[],
};

/// Insert or replace a node's review, keyed by `node_id`. `reviewed_at`
/// is generated by SQLite so the whole crate shares one timestamp source.
/// A NULL `notes` keeps whatever note the row already carries — a status
/// flip without notes must not clobber the ingest audit's note — while a
/// non-NULL value replaces it.
const UPSERT_SQL: &str = "INSERT INTO node_reviews \
     (intake_id, scope, reviewed_at, reviewed_by, status, notes) \
     VALUES (:intake_id, :scope, strftime('%Y-%m-%dT%H:%M:%SZ', 'now'), \
             :reviewed_by, :status, :notes) \
     ON CONFLICT(intake_id, scope) DO UPDATE SET \
       reviewed_at = excluded.reviewed_at, \
       reviewed_by = excluded.reviewed_by, \
       status = excluded.status, \
       notes = COALESCE(excluded.notes, node_reviews.notes)";

/// Open a `pending` row, or refresh the row already there. A `pending`
/// row takes the new reviewer token and timestamp; any other row keeps
/// its verdict, reviewer, and timestamp. `notes` is replaced on both.
/// `:pending` binds [`STATUS_PENDING`]; `RETURNING` yields the status
/// the row holds after the write.
const PIPELINE_REVIEW_SQL: &str = "INSERT INTO node_reviews \
     (intake_id, scope, reviewed_at, reviewed_by, status, notes) \
     VALUES (:intake_id, :scope, strftime('%Y-%m-%dT%H:%M:%SZ', 'now'), \
             :reviewed_by, :pending, :notes) \
     ON CONFLICT(intake_id, scope) DO UPDATE SET \
       reviewed_at = CASE WHEN node_reviews.status = :pending \
                     THEN excluded.reviewed_at ELSE node_reviews.reviewed_at END, \
       reviewed_by = CASE WHEN node_reviews.status = :pending \
                     THEN excluded.reviewed_by ELSE node_reviews.reviewed_by END, \
       notes = excluded.notes \
     RETURNING status";

/// Replace `notes` on an existing row and nothing else. No `INSERT`
/// leg: see [`Catalog::update_review_notes`].
const UPDATE_NOTES_SQL: &str = "UPDATE node_reviews SET notes = :notes \
     WHERE intake_id = :intake_id AND scope = :scope";

/// A `SELECT` of every column with `tail` appended; column list from
/// [`SPEC`].
fn select_sql(tail: &str) -> String {
    format!("SELECT {} FROM node_reviews {tail}", SPEC.select_list())
}

/// One `node_reviews` row — the outcome of one node's review.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NodeReview {
    /// The book whose node was reviewed — a soft reference to the
    /// `intake` registry.
    pub intake_id: i64,
    /// The logical address of the node within the book's partition.
    pub scope: String,
    /// When the review was made, ISO-8601 UTC.
    pub reviewed_at: String,
    /// Who made the review.
    pub reviewed_by: String,
    /// The review outcome (`pending` / `approved` / `acknowledged` /
    /// `rejected`). See the module-level documentation.
    pub status: String,
    /// Free-form notes.
    pub notes: Option<String>,
}

impl NodeReview {
    /// Build a [`NodeReview`] from a row that includes every column.
    fn from_row(row: &Row<'_>) -> rusqlite::Result<NodeReview> {
        Ok(NodeReview {
            intake_id: row.get("intake_id")?,
            scope: row.get("scope")?,
            reviewed_at: row.get("reviewed_at")?,
            reviewed_by: row.get("reviewed_by")?,
            status: row.get("status")?,
            notes: row.get("notes")?,
        })
    }
}

/// A review about to be written.
#[derive(Debug, Clone)]
pub struct NewReview {
    intake_id: i64,
    scope: String,
    reviewed_by: String,
    status: String,
    notes: Option<String>,
}

impl NewReview {
    /// A review of the node at `(intake_id, scope)` with the given
    /// outcome. Without [`NewReview::notes`] the row is inserted with a
    /// NULL note, and on conflict the stored note is left in place.
    pub fn new(
        intake_id: i64,
        kind: ItemKind,
        reviewed_by: impl Into<String>,
        status: impl Into<String>,
    ) -> NewReview {
        NewReview {
            intake_id,
            scope: kind.as_scope_str().to_string(),
            reviewed_by: reviewed_by.into(),
            status: status.into(),
            notes: None,
        }
    }

    /// Attach free-form notes, replacing any stored note on upsert.
    pub fn notes(mut self, notes: impl Into<String>) -> NewReview {
        self.notes = Some(notes.into());
        self
    }
}

impl Catalog {
    /// Insert or replace a node's review.
    pub fn upsert_review(&self, new: &NewReview) -> Result<()> {
        self.conn.execute(
            UPSERT_SQL,
            named_params! {
                ":intake_id": new.intake_id,
                ":scope": new.scope,
                ":reviewed_by": new.reviewed_by,
                ":status": new.status,
                ":notes": new.notes,
            },
        )?;
        Ok(())
    }

    /// Write the review row for a node the pipeline has just derived,
    /// with `notes` carrying its audit report. Returns the status the
    /// row holds afterwards.
    ///
    /// - No row: a [`STATUS_PENDING`] row attributed to `reviewed_by`
    ///   is inserted.
    /// - A [`STATUS_PENDING`] row: `reviewed_by` and `reviewed_at` are
    ///   re-stamped, so the row names the run that last wrote it.
    /// - Any other status: only `notes` is replaced. The verdict, its
    ///   reviewer, and its timestamp stay, as with
    ///   [`Catalog::update_review_notes`], and the returned status is
    ///   that verdict.
    ///
    /// A verdict is kept whether or not the re-derived content differs
    /// from what was reviewed. [`Catalog::upsert_review`] is the write
    /// that moves a status.
    pub fn record_pipeline_review(
        &self,
        intake_id: i64,
        kind: ItemKind,
        reviewed_by: &str,
        notes: &str,
    ) -> Result<String> {
        let status = self.conn.query_row(
            PIPELINE_REVIEW_SQL,
            named_params! {
                ":intake_id": intake_id,
                ":scope": kind.as_scope_str(),
                ":reviewed_by": reviewed_by,
                ":pending": STATUS_PENDING,
                ":notes": notes,
            },
            |row| row.get(0),
        )?;
        Ok(status)
    }

    /// Replace one review row's `notes`, leaving `status`,
    /// `reviewed_by`, and `reviewed_at` exactly as they are. Returns
    /// whether a row was there to update.
    ///
    /// This is the mirror of [`Catalog::upsert_review`], which
    /// preserves notes across a status change: a recomputation that
    /// refreshes the stored report has the opposite need, and routing
    /// it through the upsert would flip an `approved` row back to
    /// whatever status the caller passed.
    ///
    /// A missing row is not inserted. The row is the review queue's
    /// work item, opened when the item was taken in; a recomputation
    /// does not open one.
    pub fn update_review_notes(&self, intake_id: i64, kind: ItemKind, notes: &str) -> Result<bool> {
        let affected = self.conn.execute(
            UPDATE_NOTES_SQL,
            named_params! {
                ":intake_id": intake_id,
                ":scope": kind.as_scope_str(),
                ":notes": notes,
            },
        )?;
        Ok(affected > 0)
    }

    /// Number of node reviews whose `status` falls in `statuses`. An
    /// empty slice means "no filter" and counts every row.
    pub fn count_node_reviews_by_status(&self, statuses: &[&str]) -> Result<u64> {
        if statuses.is_empty() {
            let n: i64 = self
                .conn
                .query_row("SELECT COUNT(*) FROM node_reviews", [], |row| row.get(0))?;
            return count_as_u64(n);
        }
        debug_assert!(
            statuses.len() <= 8,
            "count_node_reviews_by_status takes at most 8 statuses, got {}",
            statuses.len()
        );
        let placeholders = vec!["?"; statuses.len()].join(", ");
        let sql = format!("SELECT COUNT(*) FROM node_reviews WHERE status IN ({placeholders})");
        let n: i64 =
            self.conn
                .query_row(&sql, params_from_iter(statuses.iter().copied()), |row| {
                    row.get(0)
                })?;
        count_as_u64(n)
    }

    /// Fetch the review of the node at `(intake_id, scope)`, or `None` if
    /// it has not been reviewed.
    pub fn review(&self, intake_id: i64, kind: ItemKind) -> Result<Option<NodeReview>> {
        let review = self
            .conn
            .query_row(
                &select_sql("WHERE intake_id = :intake_id AND scope = :scope"),
                named_params! { ":intake_id": intake_id, ":scope": kind.as_scope_str() },
                NodeReview::from_row,
            )
            .optional()?;
        Ok(review)
    }

    /// Fetch the review of each node at `(intake_id, scope)` for every
    /// `intake_id` in `intake_ids`, in one query. Intakes with no review
    /// row are absent from the returned map.
    ///
    /// An empty `intake_ids` slice returns an empty map without
    /// touching the database.
    pub fn reviews_for_addresses(
        &self,
        intake_ids: &[i64],
        kind: ItemKind,
    ) -> Result<BTreeMap<i64, NodeReview>> {
        if intake_ids.is_empty() {
            return Ok(BTreeMap::new());
        }
        let placeholders = vec!["?"; intake_ids.len()].join(", ");
        let sql = format!(
            "SELECT {cols} FROM node_reviews \
             WHERE scope = ? AND intake_id IN ({placeholders})",
            cols = SPEC.select_list(),
        );
        let mut params: Vec<Box<dyn ToSql>> = Vec::with_capacity(intake_ids.len() + 1);
        params.push(Box::new(kind.as_scope_str().to_string()));
        for id in intake_ids {
            params.push(Box::new(*id));
        }
        let mut stmt = self.conn.prepare(&sql)?;
        let refs: Vec<&dyn ToSql> = params.iter().map(|b| b.as_ref()).collect();
        let rows = stmt.query_map(params_from_iter(refs), NodeReview::from_row)?;
        let mut out: BTreeMap<i64, NodeReview> = BTreeMap::new();
        for row in rows {
            let row = row?;
            out.insert(row.intake_id, row);
        }
        Ok(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A logical address used throughout these tests.
    const KIND: ItemKind = ItemKind::Book;

    /// `node_reviews` is a shared write target: the ingest pipeline
    /// writes `scope = 'book'` rows and glean writes `scope = 'paper'`
    /// rows on the same key shape. Glean's paper-side dimensions
    /// (per-field grades, per-flag booleans) live on `node_paper_audit`
    /// instead of widening this table — so this test pins the column
    /// list and any structural drift here is a build-time failure.
    #[test]
    fn node_reviews_spec_columns_are_pinned() {
        let actual: Vec<&str> = SPEC.columns.iter().map(|c| c.name).collect();
        assert_eq!(
            actual,
            [
                "intake_id",
                "scope",
                "reviewed_at",
                "reviewed_by",
                "status",
                "notes"
            ],
            "node_reviews schema must not absorb paper-only audit columns",
        );
    }

    /// Refreshing the stored report must not disturb the reviewer's
    /// own verdict. Routing this through `upsert_review` would set
    /// `status` to whatever the caller passed, which for a
    /// recomputation is a value it has no business choosing.
    #[test]
    fn update_review_notes_replaces_the_note_and_leaves_the_verdict() {
        let catalog = Catalog::open_in_memory().expect("open");
        catalog
            .upsert_review(&NewReview::new(1, KIND, "human:reviewer", STATUS_APPROVED).notes("old"))
            .expect("seed");

        assert!(
            catalog
                .update_review_notes(1, KIND, "fresh report")
                .expect("update"),
            "an existing row must report as updated",
        );

        let read = catalog.review(1, KIND).expect("read").expect("present");
        assert_eq!(read.notes.as_deref(), Some("fresh report"));
        assert_eq!(read.status, STATUS_APPROVED, "the verdict must not move");
        assert_eq!(read.reviewed_by, "human:reviewer");
    }

    /// A recomputation does not open a work item. The review row is
    /// the queue's, created when the item was taken in.
    #[test]
    fn update_review_notes_does_not_insert_a_missing_row() {
        let catalog = Catalog::open_in_memory().expect("open");
        assert!(
            !catalog
                .update_review_notes(404, KIND, "report")
                .expect("update"),
            "a missing row must report as untouched",
        );
        assert!(catalog.review(404, KIND).expect("read").is_none());
    }

    /// A `reviewed_at` no write in a test run can generate.
    const BACKDATED: &str = "2000-01-01T00:00:00Z";

    /// Move a row's `reviewed_at` to [`BACKDATED`], so a kept timestamp
    /// reads apart from a re-stamped one.
    fn backdate(catalog: &Catalog, intake_id: i64) {
        catalog
            .conn
            .execute(
                "UPDATE node_reviews SET reviewed_at = :at WHERE intake_id = :intake_id",
                named_params! { ":at": BACKDATED, ":intake_id": intake_id },
            )
            .expect("backdate");
    }

    #[test]
    fn record_pipeline_review_opens_a_pending_row() {
        let catalog = Catalog::open_in_memory().expect("open");
        let status = catalog
            .record_pipeline_review(1, KIND, "bookrack-ingest:default", "report")
            .expect("write");
        assert_eq!(status, STATUS_PENDING);

        let read = catalog.review(1, KIND).expect("read").expect("present");
        assert_eq!(read.status, STATUS_PENDING);
        assert_eq!(read.reviewed_by, "bookrack-ingest:default");
        assert!(!read.reviewed_at.is_empty());
        assert_eq!(read.notes.as_deref(), Some("report"));
    }

    /// A row still waiting for a reviewer names the run that last
    /// wrote it.
    #[test]
    fn record_pipeline_review_restamps_a_pending_row() {
        let catalog = Catalog::open_in_memory().expect("open");
        catalog
            .record_pipeline_review(1, KIND, "bookrack-ingest:default", "first report")
            .expect("first pass");
        backdate(&catalog, 1);

        let status = catalog
            .record_pipeline_review(1, KIND, "bookrack-ingest:trust-source", "second report")
            .expect("second pass");
        assert_eq!(status, STATUS_PENDING);

        let read = catalog.review(1, KIND).expect("read").expect("present");
        assert_eq!(read.status, STATUS_PENDING);
        assert_eq!(read.reviewed_by, "bookrack-ingest:trust-source");
        assert_ne!(read.reviewed_at, BACKDATED, "the row must be re-stamped");
        assert_eq!(read.notes.as_deref(), Some("second report"));
    }

    /// A pipeline pass refreshes the report under a verdict and leaves
    /// the verdict, its reviewer, and its timestamp alone.
    #[test]
    fn record_pipeline_review_keeps_a_verdict_and_refreshes_its_report() {
        for verdict in [STATUS_APPROVED, STATUS_ACKNOWLEDGED, STATUS_REJECTED] {
            let catalog = Catalog::open_in_memory().expect("open");
            catalog
                .record_pipeline_review(1, KIND, "bookrack-ingest:default", "first report")
                .expect("first pass");
            catalog
                .upsert_review(&NewReview::new(1, KIND, "human:reviewer", verdict))
                .expect("verdict");
            backdate(&catalog, 1);

            let status = catalog
                .record_pipeline_review(1, KIND, "bookrack-ingest:default", "second report")
                .expect("second pass");
            assert_eq!(status, verdict, "the returned status is the kept verdict");

            let read = catalog.review(1, KIND).expect("read").expect("present");
            assert_eq!(read.status, verdict, "{verdict}: the verdict must not move");
            assert_eq!(read.reviewed_by, "human:reviewer", "{verdict}");
            assert_eq!(read.reviewed_at, BACKDATED, "{verdict}");
            assert_eq!(read.notes.as_deref(), Some("second report"), "{verdict}");
        }
    }

    #[test]
    fn a_review_round_trips_every_field() {
        let catalog = Catalog::open_in_memory().expect("open");
        catalog
            .upsert_review(
                &NewReview::new(1, KIND, "human", STATUS_ACKNOWLEDGED).notes("check the TOC"),
            )
            .expect("write");

        let read = catalog.review(1, KIND).expect("read").expect("present");
        assert_eq!(read.intake_id, 1);
        assert_eq!(read.scope, KIND.as_scope_str());
        assert!(!read.reviewed_at.is_empty());
        assert_eq!(read.reviewed_by, "human");
        assert_eq!(read.status, STATUS_ACKNOWLEDGED);
        assert_eq!(read.notes.as_deref(), Some("check the TOC"));
    }

    #[test]
    fn a_missing_review_reads_as_none() {
        let catalog = Catalog::open_in_memory().expect("open");
        assert!(catalog.review(404, KIND).expect("read").is_none());
    }

    #[test]
    fn count_node_reviews_by_status_filters_and_sums() {
        let catalog = Catalog::open_in_memory().expect("open");
        catalog
            .upsert_review(&NewReview::new(1, KIND, "human", STATUS_PENDING))
            .expect("write");
        catalog
            .upsert_review(&NewReview::new(2, KIND, "human", STATUS_APPROVED))
            .expect("write");
        catalog
            .upsert_review(&NewReview::new(3, KIND, "human", STATUS_REJECTED))
            .expect("write");

        assert_eq!(
            catalog
                .count_node_reviews_by_status(&[STATUS_PENDING])
                .expect("count pending"),
            1
        );
        assert_eq!(
            catalog
                .count_node_reviews_by_status(&[STATUS_APPROVED, STATUS_REJECTED])
                .expect("count in-list"),
            2
        );
        // Empty slice ≡ count everything.
        assert_eq!(
            catalog
                .count_node_reviews_by_status(&[])
                .expect("count all"),
            3
        );
    }

    #[test]
    fn upsert_overwrites_a_previous_review() {
        let catalog = Catalog::open_in_memory().expect("open");
        catalog
            .upsert_review(&NewReview::new(1, KIND, "human", STATUS_PENDING))
            .expect("first review");
        catalog
            .upsert_review(&NewReview::new(1, KIND, "human", STATUS_APPROVED))
            .expect("second review");
        let read = catalog.review(1, KIND).expect("read").expect("present");
        assert_eq!(read.status, STATUS_APPROVED);
    }

    #[test]
    fn upsert_without_notes_preserves_the_stored_note() {
        let catalog = Catalog::open_in_memory().expect("open");
        catalog
            .upsert_review(
                &NewReview::new(1, KIND, "bookrack-ingest:default", STATUS_PENDING)
                    .notes("audit verdict=clean, all audited fields clean"),
            )
            .expect("ingest review");
        catalog
            .upsert_review(&NewReview::new(1, KIND, "human", STATUS_APPROVED))
            .expect("status flip");
        let read = catalog.review(1, KIND).expect("read").expect("present");
        assert_eq!(read.status, STATUS_APPROVED);
        assert_eq!(
            read.notes.as_deref(),
            Some("audit verdict=clean, all audited fields clean")
        );

        catalog
            .upsert_review(&NewReview::new(1, KIND, "human", STATUS_APPROVED).notes("replacement"))
            .expect("notes replace");
        let read = catalog.review(1, KIND).expect("read").expect("present");
        assert_eq!(read.notes.as_deref(), Some("replacement"));
    }

    #[test]
    fn reviews_for_addresses_empty_input_skips_the_query() {
        let catalog = Catalog::open_in_memory().expect("open");
        let map = catalog.reviews_for_addresses(&[], KIND).expect("read");
        assert!(map.is_empty());
    }

    #[test]
    fn reviews_for_addresses_returns_only_matching_rows() {
        let catalog = Catalog::open_in_memory().expect("open");
        catalog
            .upsert_review(&NewReview::new(1, KIND, "human", STATUS_APPROVED))
            .expect("write 1");
        catalog
            .upsert_review(&NewReview::new(2, KIND, "human", STATUS_PENDING))
            .expect("write 2");
        // A row at another scope must not leak into a book-scope batch.
        catalog
            .upsert_review(&NewReview::new(
                3,
                ItemKind::Paper,
                "human",
                STATUS_APPROVED,
            ))
            .expect("write 3.paper");

        let map = catalog
            .reviews_for_addresses(&[1, 2, 3, 404], KIND)
            .expect("read");
        assert_eq!(map.len(), 2);
        assert_eq!(map[&1].status, STATUS_APPROVED);
        assert_eq!(map[&2].status, STATUS_PENDING);
    }
}
